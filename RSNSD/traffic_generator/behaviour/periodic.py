"""
Periodic Traffic Behaviour

Models periodic telemetry generated by IoT devices.

Typical applications:
- Soil Monitoring
- Weather Station
- Smart Irrigation
- Livestock Monitoring
- Health Monitoring
- Environmental Sensors

Author: RSNSD
"""

from __future__ import annotations

import random

from RSNSD.traffic_generator.behaviour.base_behaviour import BaseBehaviour


class PeriodicBehaviour(BaseBehaviour):
    """
    Periodic telemetry traffic.

    Characteristics
    ---------------
    - Small packets
    - Fixed reporting interval
    - Very low bitrate
    - Long-lived sessions
    - Minimal burstiness
    """

    @property
    def name(self) -> str:
        return "periodic"

    def generate_idle_time(self) -> float:
        """
        Idle time corresponds to the interval
        between periodic transmissions.
        """

        return round(
            random.uniform(
                0.5,
                5.0,
            ),
            2,
        )

    def generate_burst_size(self) -> int:
        """
        A telemetry transmission typically
        contains one or two packets.
        """

        return random.randint(
            1,
            2,
        )

    def generate_connection_probability(self) -> float:
        """
        IoT devices are almost always connected.
        """

        return 0.98